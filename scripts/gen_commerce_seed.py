i = 0
while _diff != 0:
    step = 1 if _diff > 0 else -1
    if 1 <= LINE_COUNTS[i % 40] + step <= 4:
        LINE_COUNTS[i % 40] += step
        _diff -= step
    i += 1


def q(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def ago(minutes):
    return f"date_sub(now(6), interval {minutes} minute)"


def main():
    out = []
    w = out.append
    w("-- Demo commerce data (proposal 7.2). Generated by scripts/gen_commerce_seed.py: do not edit by hand.")
    w("-- Runs only with the \"demo\" profile. Needs the catalog seed (products and variants) to have a lower version.")
    w("")
    w("-- ---------------------------------------------------------------- vouchers")
    for code, vtype, value, mx, mn, d1, d2, limit in VOUCHERS:
        w("insert into vouchers (created_at, created_by, code, type, discount_value, max_discount_amount, "
          "min_order_amount, start_date, end_date, usage_limit, used_count, is_active) values "
          f"(now(6), 'seed', {q(code)}, '{vtype}', {value}, {mx if mx is not None else 'null'}, {mn}, "
          f"date_add(now(6), interval {d1} day), date_add(now(6), interval {d2} day), {limit}, 0, b'1');")
    w("")
    w("-- ------------------------------------------------------------------ users")
    for n, name in enumerate(NAMES, start=1):
        email = f"khach{n:02d}@welo-demo.vn"
        phone = f"0901{n:06d}"
        w("insert into users (account_status, created_at, created_by, email, password, role, phone, email_verified, full_name) "
          f"values ('ACTIVE', {ago(60 * 24 * (70 - n))}, 'seed', {q(email)}, {q(PASSWORD_HASH)}, 'CUSTOMER', {q(phone)}, b'1', {q(name)});")
    w("")
    w("-- ------------------------------------------------------------------ orders")
    orders = []
    for status, count, (lo, hi) in STATUS_PLAN:
        for k in range(count):
            days = lo + (hi - lo) * k // max(count - 1, 1)
            orders.append((status, days))
    assigned = 0
    for idx, (status, days) in enumerate(orders, start=1):
        user_no = (idx * 7) % len(NAMES) + 1
        email = f"khach{user_no:02d}@welo-demo.vn"
        voucher = None
        if idx % 3 != 0:  # two orders out of three carry a voucher, taken in turn
            voucher = USABLE[assigned % len(USABLE)]
            assigned += 1
        placed = days * 1440 + (idx * 37) % 600 + 5
        key = f"seed-order-{idx:02d}"
        voucher_sql = f"(select id from vouchers where code = {q(voucher)})" if voucher else "null"
        w("insert into orders (created_at, created_by, user_id, voucher_id, status, payment_method, shipping_address_text, "
          "idempotency_key, total_amount, shipping_fee, discount_amount, shipping_discount) values "
          f"({ago(placed)}, 'seed', (select id from users where email = {q(email)}), {voucher_sql}, '{status}', 'COD', "
          f"{q(ADDRESSES[idx % len(ADDRESSES)])}, {q(key)}, 0, {SHIPPING_FEE}, 0, 0);")
    w("")
    w("-- ------------------------------------------------------- order lines (about 90)")
    for idx in range(1, len(orders) + 1):
        key = f"seed-order-{idx:02d}"
        for j in range(LINE_COUNTS[idx - 1]):
            k = idx * 7 + j * 13
            qty = 1 + (idx + j) % 3
            w("insert into order_items (order_id, product_variant_id, quantity, unit_price) "
              f"select o.id, v.id, {qty}, p.base_price from orders o "
              "join (select id, product_id from (select id, product_id, row_number() over (order by id) rn from product_variants) t "
              f"where rn = 1 + mod({k}, nullif((select count(*) from product_variants), 0))) v "
              f"join products p on p.id = v.product_id where o.idempotency_key = {q(key)};")
    w("")
    w("-- orders that found no variant to buy are removed again (their history is not created yet)")
    w("delete o from orders o left join order_items i on i.order_id = o.id "
      "where o.idempotency_key like 'seed-order-%' and i.id is null;")
    w("")
    w("-- a voucher stays on an order only when the order reached its minimum amount")
    w("update orders o join (select order_id, sum(quantity * unit_price) subtotal from order_items group by order_id) s on s.order_id = o.id "
      "join vouchers v on v.id = o.voucher_id set o.voucher_id = null "
      "where o.idempotency_key like 'seed-order-%' and s.subtotal < v.min_order_amount;")
    w("")
    w("-- money: the same rules as the application (proposal 6.3)")
    w("update orders o join (select order_id, sum(quantity * unit_price) subtotal from order_items group by order_id) s on s.order_id = o.id "
      "left join vouchers v on v.id = o.voucher_id set "
      "o.discount_amount = case "
      "when v.type = 'PERCENT' then least(round(s.subtotal * v.discount_value / 100, 2), coalesce(v.max_discount_amount, s.subtotal), s.subtotal) "
      "when v.type = 'FIXED_AMOUNT' then least(v.discount_value, s.subtotal) else 0 end, "
      f"o.shipping_discount = case when v.type = 'FREESHIP' then least(case when v.discount_value = 0 then {SHIPPING_FEE} else v.discount_value end, {SHIPPING_FEE}) else 0 end "
      "where o.idempotency_key like 'seed-order-%';")
    w("update orders o join (select order_id, sum(quantity * unit_price) subtotal from order_items group by order_id) s on s.order_id = o.id "
      "set o.total_amount = s.subtotal - o.discount_amount + o.shipping_fee - o.shipping_discount "
      "where o.idempotency_key like 'seed-order-%';")
    w("")
    w("-- ------------------------------------------------------ status history")
    for idx, (status, days) in enumerate(orders, start=1):
        key = f"seed-order-{idx:02d}"
        user_no = (idx * 7) % len(NAMES) + 1
        customer = f"khach{user_no:02d}@welo-demo.vn"
        placed = days * 1440 + (idx * 37) % 600 + 5
        steps = [(None, "PENDING_CONFIRMATION", customer, "Order placed", placed)]
        if status == "CANCELLED":
            if idx % 2 == 0:
                steps.append(("PENDING_CONFIRMATION", "CANCELLED", customer, "Cancelled by customer", placed - 90))
            else:
                steps.append(("PENDING_CONFIRMATION", "AWAITING_PICKUP", "seed-staff", None, placed - 120))
                steps.append(("AWAITING_PICKUP", "CANCELLED", "seed-staff", "Out of stock at the warehouse", placed - 300))
        else:
            chain = ["PENDING_CONFIRMATION", "AWAITING_PICKUP", "SHIPPING", "DELIVERED", "COMPLETED"]
            reach = chain.index(status)
            minutes = placed
            for pos in range(1, reach + 1):
                minutes -= {1: 120, 2: 1440, 3: 2880, 4: 1440}[pos]
                minutes = max(minutes, 1)
                actor = customer if chain[pos] == "COMPLETED" else "seed-staff"
                reason = "Customer confirmed receipt" if chain[pos] == "COMPLETED" else None
                steps.append((chain[pos - 1], chain[pos], actor, reason, minutes))
        for frm, to, who, reason, m in steps:
            w("insert into order_status_history (order_id, from_status, to_status, changed_by, reason, changed_at) "
              f"select o.id, {q(frm) if frm else 'null'}, '{to}', {q(who)}, {q(reason) if reason else 'null'}, {ago(max(m, 1))} "
              f"from orders o where o.idempotency_key = {q(key)};")
    w("")
    w("-- ---------------------------------------------------- voucher use counts")
    w("insert into voucher_usages (voucher_id, user_id, order_id, used_at) "
      "select o.voucher_id, o.user_id, o.id, o.created_at from orders o "
      "where o.idempotency_key like 'seed-order-%' and o.voucher_id is not null and o.status <> 'CANCELLED';")
    w("update vouchers v set v.used_count = (select count(*) from voucher_usages u where u.voucher_id = v.id) "
      "where v.created_by = 'seed';")
    w("")

    target = os.path.join(os.path.dirname(__file__), "..", "backend", "webApplication", "src", "main",
                          "resources", "db", "seed-demo", "V200__demo_commerce_seed.sql")
    target = os.path.normpath(target)
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {target}: {len(out)} lines, {len(orders)} orders, {sum(LINE_COUNTS)} lines")


if __name__ == "__main__":
    main()
