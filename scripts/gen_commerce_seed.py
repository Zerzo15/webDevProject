# status, how many orders, (min days ago, max days ago) of the placing time
STATUS_PLAN = [
    ("PENDING_CONFIRMATION", 6, (0, 2)),
    ("AWAITING_PICKUP", 5, (2, 4)),
    ("SHIPPING", 4, (4, 7)),
    ("DELIVERED", 6, (8, 14)),
    ("COMPLETED", 14, (15, 55)),
    ("CANCELLED", 5, (1, 40)),
]
LINE_COUNTS = [2, 3, 2, 1, 3, 2, 2, 3, 1, 2] * 4
LINE_COUNTS[-1] += 0
# make the total exactly 90 lines
